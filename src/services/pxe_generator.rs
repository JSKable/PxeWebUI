use crate::models::{Iso, Settings};

pub struct PxeGenerator;

impl PxeGenerator {
    pub fn generate_ipxe_script(
        settings: &Settings,
        isos: &[Iso],
        server_ip: &str,
        http_port: u16,
    ) -> String {
        let mut script = String::new();

        script.push_str("#!ipxe\n");
        script.push_str("## Auto-generated by PxeWebUI Network Boot Engine\n");
        script.push_str("## https://github.com/PxeWebUI\n\n");

        // Styling & Console Configuration
        script.push_str("set esc:hex 1b\n");
        script.push_str("set bold ${esc:string}[1m\n");
        script.push_str("set reset ${esc:string}[0m\n\n");

        script.push_str("console --picture --keep ||\n");
        script.push_str("colour --rgb 0x0ea5e9 1 ||\n"); // Tailwind Sky-500
        script.push_str("colour --rgb 0x64748b 2 ||\n"); // Slate-500
        script.push_str("colour --rgb 0x22c55e 3 ||\n"); // Green-500
        script.push_str("colour --rgb 0xef4444 4 ||\n\n"); // Red-500

        // Server Variables
        script.push_str(&format!("set server_ip {}\n", server_ip));
        script.push_str(&format!("set server_port {}\n", http_port));
        script.push_str("set base_url http://${server_ip}:${server_port}\n\n");

        // Timeout and default action
        let timeout_ms = settings.boot_timeout * 1000;
        let default_target = match settings.default_boot_action.as_str() {
            "first_iso" => {
                if let Some(first) = isos.iter().find(|i| i.is_enabled) {
                    format!("iso_{}", first.id)
                } else {
                    "local".to_string()
                }
            }
            action if action.starts_with("iso:") => {
                let id = &action[4..];
                format!("iso_{}", id)
            }
            _ => "local".to_string(),
        };

        // Main Menu Definition
        script.push_str(":start\n");
        script.push_str(&format!(
            "menu {} (Timeout: {}s)\n",
            settings.menu_title, settings.boot_timeout
        ));
        script.push_str("item --gap --             ---------------- Operating Systems & Tools ----------------\n");

        for iso in isos.iter().filter(|i| i.is_enabled) {
            let badge = match iso.category.as_str() {
                "linux" => "[Linux]",
                "windows" => "[Windows]",
                "hypervisor" => "[Hypervisor]",
                "utility" => "[Utility]",
                _ => "[Custom]",
            };

            let arch_badges = format!(
                "{}{}{}",
                if iso.arch_bios { " BIOS" } else { "" },
                if iso.arch_uefi64 { " UEFI64" } else { "" },
                if iso.secure_boot_supported { " [SB]" } else { "" }
            );

            let desc = if !iso.description.is_empty() {
                format!(" - {}", iso.description)
            } else {
                String::new()
            };

            script.push_str(&format!(
                "item iso_{} {} {} {}{}\n",
                iso.id, badge, iso.title, arch_badges, desc
            ));
        }

        script.push_str("item --gap --             ---------------- System Actions ----------------\n");
        script.push_str("item local                Boot from Local Drive (Default)\n");
        script.push_str("item netinfo              View Network & Client Diagnostics\n");
        script.push_str("item shell                Drop to iPXE Interactive Shell\n");
        script.push_str("item reboot               Reboot System\n");
        script.push_str("item poweroff             Power Off System\n\n");

        script.push_str(&format!(
            "choose --timeout {} --default {} target && goto ${{target}}\n\n",
            timeout_ms, default_target
        ));

        // System Action Handlers
        script.push_str(":local\n");
        script.push_str("echo Booting from local storage...\n");
        script.push_str("sanboot --no-describe --drive 0x80 || exit 1\n\n");

        script.push_str(":netinfo\n");
        script.push_str("echo IP address:    ${net0/ip} / ${net0/netmask}\n");
        script.push_str("echo Gateway:       ${net0/gateway}\n");
        script.push_str("echo DNS:           ${net0/dns}\n");
        script.push_str("echo MAC address:   ${net0/mac}\n");
        script.push_str("echo Platform:      ${platform} (${buildarch})\n");
        script.push_str("echo Boot Server:   ${server_ip}:${server_port}\n");
        script.push_str("prompt --key 0x02 --timeout 5000 Press CTRL-B or any key to return...\n");
        script.push_str("goto start\n\n");

        script.push_str(":shell\n");
        script.push_str("echo Type 'exit' to return to menu.\n");
        script.push_str("shell\n");
        script.push_str("goto start\n\n");

        script.push_str(":reboot\n");
        script.push_str("reboot\n\n");

        script.push_str(":poweroff\n");
        script.push_str("poweroff\n\n");

        // Generate boot target routines for each ISO
        for iso in isos.iter().filter(|i| i.is_enabled) {
            script.push_str(&format!(":iso_{}\n", iso.id));
            script.push_str(&format!("echo Loading {}...\n", iso.title));

            if let Some(ref custom) = iso.custom_ipxe {
                if !custom.trim().is_empty() {
                    script.push_str(&format!("{}\n", custom.trim()));
                    script.push_str("boot || goto failed\n\n");
                    continue;
                }
            }

            match iso.boot_mode.as_str() {
                "memdisk" => {
                    script.push_str("iseq ${platform} pcbios && goto memdisk_bios || goto memdisk_uefi\n");
                    script.push_str(":memdisk_bios\n");
                    script.push_str("kernel ${base_url}/tftp/memdisk iso raw\n");
                    script.push_str(&format!("initrd ${{base_url}}/iso/{}\n", iso.filename));
                    script.push_str("boot || goto failed\n");
                    script.push_str(":memdisk_uefi\n");
                    script.push_str("echo MEMDISK is only supported on Legacy BIOS. Attempting HTTP SANBOOT...\n");
                    script.push_str(&format!(
                        "sanboot --no-describe ${{base_url}}/iso/{} || goto failed\n\n",
                        iso.filename
                    ));
                }
                "wimboot" => {
                    script.push_str("kernel ${base_url}/tftp/wimboot\n");
                    script.push_str(&format!("initrd ${{base_url}}/iso/{}\n", iso.filename));
                    script.push_str("boot || goto failed\n\n");
                }
                "kernel_initrd" => {
                    let kargs = iso.kernel_args.as_deref().unwrap_or("boot=casper netboot=nfs");
                    script.push_str(&format!("kernel ${{base_url}}/boot/vmlinuz {}\n", kargs));
                    script.push_str("initrd ${base_url}/boot/initrd.img\n");
                    script.push_str("boot || goto failed\n\n");
                }
                _ => {
                    // Default: sanboot
                    script.push_str(&format!(
                        "sanboot --no-describe ${{base_url}}/iso/{} || goto failed\n\n",
                        iso.filename
                    ));
                }
            }
        }

        // Failure handler
        script.push_str(":failed\n");
        script.push_str("echo Boot failed! Press any key to return to menu...\n");
        script.push_str("prompt\n");
        script.push_str("goto start\n");

        script
    }

    pub fn generate_grub_cfg(
        settings: &Settings,
        isos: &[Iso],
        server_ip: &str,
        http_port: u16,
    ) -> String {
        let mut cfg = String::new();
        cfg.push_str("# GRUB Network Boot Configuration - PxeWebUI (Secure Boot Compatible)\n");
        cfg.push_str(&format!("set timeout={}\n", settings.boot_timeout));
        cfg.push_str("set default=0\n\n");

        cfg.push_str("menuentry 'Boot from Local Drive' {\n");
        cfg.push_str("    exit\n");
        cfg.push_str("}\n\n");

        for iso in isos.iter().filter(|i| i.is_enabled && i.arch_uefi64) {
            cfg.push_str(&format!("menuentry '{}' {{\n", iso.title));
            cfg.push_str(&format!(
                "    echo 'Chainloading iPXE for {}...'\n",
                iso.title
            ));
            cfg.push_str(&format!(
                "    chainloader (http,{},{})/tftp/ipxe.efi\n",
                server_ip, http_port
            ));
            cfg.push_str("}\n\n");
        }

        cfg.push_str("menuentry 'System Reboot' {\n");
        cfg.push_str("    reboot\n");
        cfg.push_str("}\n\n");

        cfg.push_str("menuentry 'System Shutdown' {\n");
        cfg.push_str("    halt\n");
        cfg.push_str("}\n");

        cfg
    }
}
